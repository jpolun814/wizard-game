"""The cracks that show on a Stone Wall as it wears (scripts/terrain/rock_wall.gd): four cracks of different shape, 12 wide and 24 tall, side by side. Run it from anywhere:

    python tools/wizard_parts/cracks.py

It writes art/fx/cracks.png. Never edit the PNG by hand: change this file and run it. a = the dark crack, b = a lighter chip of stone beside it.
"""
import os
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
W, H = 12, 24
COLORS = {"a": (13, 8, 20, 255), "b": (120, 104, 130, 255)}
CRACKS = [
    ["....a.......", "....a.......", "...ab.......", "...a........", "...aa.......", "....a.......", "....aa......", ".....a......", ".....a......", "....ab......", "....a.......", "....a.......", "...aa.......", "...a........", "...a........", "..aa........", "..a.........", "..a.........", ".aa.........", ".a..........", ".a..........", "............", "............", "............"],
    ["............", "......a.....", "......a.....", ".....aa.....", ".....a......", ".....aab....", "......a.....", ".......a....", ".......aa...", "........a...", "........a...", ".......ab...", ".......a....", "......aa....", "......a.....", ".....aa.....", ".....a......", "............", "............", "............", "............", "............", "............", "............"],
    ["............", "............", "a...........", "aa..........", ".a..........", ".aa.........", "..a.........", "..aaa.......", "....a.......", "....aab.....", ".....a......", ".....a......", "......a.....", "......aa....", ".......a....", ".......a....", "............", "............", "............", "............", "............", "............", "............", "............"],
    ["............", "............", "............", "..a.........", "..a.........", "..aa........", "...a....a...", "...aa..aa...", "....aaaa....", ".....aa.....", ".....a......", ".....aab....", "......a.....", "......a.....", ".....aa.....", ".....a......", "............", "............", "............", "............", "............", "............", "............", "............"],
]


def main() -> None:
    sheet = Image.new("RGBA", (W * len(CRACKS), H), (0, 0, 0, 0))
    for k, rows in enumerate(CRACKS):
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch in COLORS:
                    sheet.putpixel((k * W + x, y), COLORS[ch])
    sheet.save(os.path.join(ROOT, "art", "fx", "cracks.png"))


main()
